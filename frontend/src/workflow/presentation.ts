const pausedVoices = /^Oops—voice generation paused at (.+)\. (?:(\d+) of (\d+) completed voices are safely saved\.|No completed voices were lost\.) Choose Continue voice generation below to resume (?:from this voice|the remaining voices)\.$/;

const referencedOperationErrors = new Set([
  "We couldn’t create the audio. Please try again.",
  "We couldn’t transcribe the voice sample. Please try again.",
  "We couldn’t read this voice sample. Please try another recording.",
  "We couldn’t create the audiobook download. Please try again.",
  "We couldn’t create this page preview. Please try again.",
  "We couldn’t read this document. Please try again or upload another file.",
]);

function referencedOperationError(value: string) {
  const matched = value.match(/^(.+) Reference: ([0-9a-f]{32})\.$/);
  return matched?.[0] === value && referencedOperationErrors.has(matched[1])
    ? { message: matched[1], reference: matched[2] }
    : undefined;
}

export function message(reason: unknown) {
  if (isActionRequiredError(reason)) return reason.handled ? '' : reason.actionRequired.message;
  const raw = reason instanceof Error ? reason.message : "";
  if (referencedOperationError(raw)) return raw;
  if (/model.+not installed/i.test(raw)) return "errors.aiUnavailable";
  if (/Wait for this book's processing to finish/i.test(raw)) return "errors.bookProcessingActive";
  if (/Could not remove this book's working files/i.test(raw)) return "errors.deleteWorkingData";
  if (/No voice auditions could be created/i.test(raw)) return "No voice auditions could be created. Try again; your accepted choices are unchanged.";
  if (/network|failed to fetch|load failed|connection|offline|timed? out|timeout/i.test(raw)) return "The connection was interrupted. Check your connection and try again. Your accepted work is unchanged.";
  if (/source integrity|imported (?:PDF|source|document).*(?:missing|integrity)|Extraction requires an imported PDF|Accept import first/i.test(raw)) return "Import the source document again before continuing.";
  if (raw === "Text file contains binary control characters") return "Save this file as plain UTF-8 text before importing.";
  if (raw === "Unsupported text document format") return "Use a PDF, EPUB, TXT, or Markdown file";
  if (raw === "EPUB archive must be 64 MiB or smaller") return "EPUB files must be 64 MiB or smaller.";
  if (raw === "The EPUB archive is malformed or unsupported" || raw === "The uploaded file is not a valid EPUB") return "This EPUB could not be read. Try another copy of the book.";
  if (raw === "Export chapters are required") return "Choose a chapter to export.";
  if (/audition recipe changed|complete audition pack/i.test(raw)) return "Your voices need refreshing before you continue.";
  if (/require an editable (?:Voice draft|Cast candidate)/i.test(raw)) return "Reopen Cast & voices to change this audition.";
  if (pausedVoices.test(raw)) return raw;
  if (/^Audio generation is temporarily rate-limited\. Completed audio is saved; try continuing generation in about one minute\.(?: Reference: [^\n]+\.)?$/.test(raw)) return "Audio generation is temporarily busy. Completed audio is saved; try continuing in about one minute.";
  if (/^Audio generation paused at one passage\. Completed audio is saved; try continuing generation\.(?: Reference: [^\n]+\.)?$/.test(raw)) return "Audio generation paused at one passage. Completed audio is saved; try continuing generation.";
  if (technicalDetail.test(raw)) return stepError;
  // Known product messages are translated and reviewed with the interface. Unknown
  // service exceptions must not turn the error banner into a diagnostics console.
  if (Object.hasOwn(zhCN, raw) || editionErrorKeys.has(raw)) return raw;
  return stepError;
}

const editionErrorKeys = new Set([
  "errors.aiUnavailable",
  "errors.bookProcessingActive",
  "errors.deleteWorkingData",
  "errors.tenantStorageLimit",
  "errors.globalStorageCapacity",
]);

export function localizeErrorMessage(value: string, t: TFunction) {
  const referenced = referencedOperationError(value);
  if (referenced) return t("{{message}} Reference: {{reference}}.", {
    message: t(referenced.message), reference: referenced.reference,
  });
  const paused = value.match(pausedVoices);
  if (paused) return t(paused[2]
    ? "Voice generation paused at {{name}}. {{completed}} of {{total}} voices are saved. Choose Continue voice generation to resume."
    : "Voice generation paused at {{name}}. No completed voices were lost. Choose Continue voice generation to resume.",
  { name: paused[1], completed: paused[2], total: paused[3] });
  return editionErrorKeys.has(value)
    ? t(value, { ns: "edition" })
    : t(value, { defaultValue: value });
}

