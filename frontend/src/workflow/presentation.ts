export function localizeProcessMessage(value: string, t: TFunction) {
  const label = processLabels[value];
  if (label) return t(label);
  if (/^Checking speaker assignments with .+$/.test(value)) return t("Checking who speaks each line");
  if (/^Checking \d+ text windows with .+$/.test(value)) return t("Checking the text for possible corrections");
  const patterns: Array<[RegExp, string, string[]]> = [
    [/^Extracted (\d+) pages$/, "Extracted {{count}} pages", ["count"]],
    [/^Extracted page (\d+) of (\d+)$/, "Extracted page {{page}} of {{count}}", ["page", "count"]],
    [/^Auditioning (.+) \((\d+) of (\d+)\)$/, "Auditioning {{name}} ({{current}} of {{count}})", ["name", "current", "count"]],
    [/^Generated voice (\d+) of (\d+): (.+)$/, "Generated voice {{current}} of {{count}}: {{name}}", ["current", "count", "name"]],
    [/^Regenerating the (.+) audition$/, "Regenerating the {{name}} audition", ["name"]],
    [/^Generating (\d+) (?:required|affected) voice auditions$/, "Generating {{count}} required voice auditions", ["count"]],
    [/^Making chapter audio from (\d+) passages$/, "Making chapter audio from {{count}} passages", ["count"]],
    [/^(?:Reviewing|Classifying and discovering) (\d+) character labels with AI$/, "Reviewing {{count}} characters", ["count"]],
    [/^Adjudicating (\d+) possible identity pairs$/, "Comparing {{count}} possible character matches", ["count"]],
    [/^Preparing (\d+) voice profiles with AI$/, "Preparing voices for {{count}} characters", ["count"]],
  ];
  for (const [pattern, key, names] of patterns) {
    const match = value.match(pattern);
    if (match) return t(key, Object.fromEntries(names.map((name, index) => [name, match[index + 1]])));
  }
  // The catalog is the reviewed product vocabulary; unknown adapter progress gets
  // a neutral ongoing status instead of leaking model names or operational data.
  if (Object.hasOwn(zhCN, value) && !technicalDetail.test(value)) return t(value);
  return t("Working on your book…");
}

export function formatFileSize(bytes: number) {
  if (bytes === 0) return "0 KB";
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} KB`;
  if (bytes < 1024 * 1024 * 1024) return `${(bytes / 1024 / 1024).toFixed(1)} MB`;
  return `${(bytes / 1024 / 1024 / 1024).toFixed(1)} GB`;
}

const audioExportBitrates: Record<AudioExportPreset, number> = {
  "m4b-high": 128,
  "m4b-compact": 64,
  "mp3-chapters": 96,
};

export function estimatedAudioExportBytes(seconds: number, preset: AudioExportPreset) {
  return Math.max(0, Math.round(seconds * audioExportBitrates[preset] * 1000 / 8));
}

export function formatLibraryExport(item: LibraryExport, t: TFunction) {
  const preset = item.preset ?? (item.filename.toLowerCase().endsWith(".zip") ? "mp3-chapters" : "m4b-high");
  if (preset === "m4b-compact") return t("Smaller M4B");
  if (preset === "mp3-chapters") return t("MP3 chapters");
  return t("High-quality M4B");
}

export function formatLibraryDate(value: string, locale: string) {
  return new Intl.DateTimeFormat(locale, { dateStyle: "medium" }).format(new Date(value));
}

export function formatLibraryChapters(item: LibraryExport, t: TFunction) {
  const positions = [...(item.chapterPositions ?? [])].sort((left, right) => left - right);
  if (!item.partial) return item.chapterCount === 1 ? t("1 chapter") : t("{{count}} chapters", { count: item.chapterCount });
  if (!positions.length) return t(item.chapterCount === 1 ? "Selected chapter" : "Selected chapters");
  const ranges: Array<[number, number]> = [];
  for (const position of positions) {
    const current = ranges.at(-1);
    if (current && position === current[1] + 1) current[1] = position;
    else ranges.push([position, position]);
  }
  if (ranges.length > 3) return t("{{count}} selected chapters", { count: item.chapterCount });
  const labels = ranges.map(([start, end]) => start === end ? `${start}` : `${start}–${end}`);
  return t(positions.length === 1 ? "Chapter {{labels}}" : "Chapters {{labels}}", { labels: labels.length === 1 ? labels[0] : `${labels.slice(0, -1).join(", ")} & ${labels.at(-1)}` });
}
