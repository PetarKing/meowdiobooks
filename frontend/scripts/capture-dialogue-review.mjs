import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
const out = new URL('../../.review-evidence/dialogue/', import.meta.url).pathname;
await mkdir(out, { recursive: true });
const browser = await chromium.launch();
const metrics = [];
for (const [label, port] of [['before', 5180], ['after', 5181]]) {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, recordVideo: { dir: out, size: { width: 390, height: 844 } }, reducedMotion: 'reduce' });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`http://127.0.0.1:${port}/dialogue-review.html`);
  await page.getByRole('heading', { name: label === 'before' ? 'Your transcript is ready' : 'Your transcript' }).waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: `${out}${label}-mobile.png`, fullPage: true });
  const accept = page.getByRole('button', { name: label === 'before' ? 'Accept dialogue result →' : 'Continue →' });
  const result = { label, initialHeight: await page.evaluate(() => document.documentElement.scrollHeight), acceptInitiallyEnabled: await accept.isEnabled(), errors };
  if (label === 'before') {
    await page.getByRole('tab', { name: 'AI checks 24' }).click();
    result.allChecksHeight = await page.evaluate(() => document.documentElement.scrollHeight);
    await page.waitForTimeout(1000);
    for (let i=0;i<5;i++) { await page.mouse.wheel(0, 580); await page.waitForTimeout(700); }
    await page.getByRole('tab', { name: 'Review 16', exact: true }).click();
    await page.mouse.wheel(0, 340); await page.waitForTimeout(1200);
  } else {
    assert.equal(await accept.isEnabled(), false);
    assert.equal(await page.getByRole('region', {name:'By reader'}).count(), 0);
    assert.equal(await page.getByRole('button', {name:'← Back to readers'}).count(), 0);
    await page.getByRole('button', {name:'Show more source context'}).click();
    await page.waitForTimeout(1000);
    await page.getByRole('button', {name:'Show less source context'}).click();
    await page.getByRole('button', {name:'Choose White Rabbit', exact:true}).click();
    await page.getByRole('button', {name:'Previous',exact:true}).click();
    assert.equal(await page.getByRole('button', {name:'Choose White Rabbit',exact:true}).getAttribute('aria-pressed'),'true');
    await page.getByRole('button', {name:'Choose Alice',exact:true}).click();
    await page.getByText('Line 1 of 24',{exact:true}).waitFor();
    await page.getByRole('button', {name:'Choose White Rabbit',exact:true}).click();
    await page.screenshot({path:`${out}after-chosen-suggestion.png`,fullPage:true});
    await page.waitForTimeout(1000);
    await page.getByRole('button', {name:'Next →'}).click();
    await page.getByRole('button', {name:'Skip for now →'}).click();
    assert.equal(await accept.isEnabled(), false);
    await page.getByRole('button', {name:'Accept all AI guesses',exact:true}).click();
    await page.getByRole('region',{name:'By reader'}).waitFor();
    assert.equal(await accept.isEnabled(), true);
    assert.equal(await page.getByRole('heading',{name:'Your transcript'}).evaluate(el => el === document.activeElement), true);
    await page.waitForTimeout(1300);
    await page.screenshot({ path: `${out}after-complete.png`, fullPage: true });
    await page.getByRole('button',{name:'Undo bulk choice'}).click();
    assert.equal(await accept.isEnabled(), false);
    await page.waitForTimeout(900);
    await page.getByRole('button',{name:'Use narrator for remaining'}).click();
    await page.waitForTimeout(900);
    await page.getByRole('button', {name:'Check your choices'}).click();
    result.allChecksHeight = await page.evaluate(() => document.documentElement.scrollHeight);
    assert.equal(await page.getByRole('region', {name:'By reader'}).count(), 0);
    await page.getByRole('button', {name:'Needs review 0'}).click();
    await page.getByText('No lines need review.',{exact:true}).waitFor();
    await page.getByRole('button', {name:'Reviewed 24'}).click();
    assert.equal(await page.getByRole('article').count(), 1);
    await page.screenshot({path:`${out}after-rechecking.png`, fullPage:true});
    await page.getByRole('button', {name:'Next →'}).click();
    await page.getByText('Line 2 of 24',{exact:true}).waitFor();
    await page.getByRole('button', {name:'← Back to readers'}).click();
    await page.getByRole('region', {name:'By reader'}).waitFor();
    await page.waitForTimeout(1000);
    await page.getByRole('button', {name:'Check your choices'}).click();
    assert.match(await page.locator('.ai-outcome').first().innerText(), /White Rabbit/);
  }
  assert.deepEqual(errors, []);
  metrics.push(result);
  const video = page.video();
  await context.close();
  await video.saveAs(`${out}${label}-mobile.webm`);
}
// Additional visual/interaction checks on the same real components and synthetic gateway.
for (const width of [320, 390, 1440]) for (const appearance of ['light', 'dark']) {
  const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:5181/dialogue-review.html?appearance=${appearance}`);
  await page.getByRole('heading',{name:'Your transcript'}).waitFor();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  assert(overflow <= 1, `${width} ${appearance}: overflow ${overflow}`);
  await page.getByRole('button',{name:'Choose another character'}).click();
  const editor = page.getByRole('combobox');
  assert.equal(await editor.evaluate(el => parseFloat(getComputedStyle(el).fontSize) >= 16 || innerWidth > 700), true);
  await editor.press('Escape');
  assert.equal(await page.getByRole('button',{name:'Choose another character'}).evaluate(el=>el===document.activeElement), true);
  await page.evaluate(() => window.scrollTo(0,0));
  await page.screenshot({path:`${out}after-${width}-${appearance}.png`, fullPage:true});
  if (width === 390 && appearance === 'light') {
    await page.getByRole('button',{name:'Choose another character'}).click();
    assert.deepEqual((await page.getByRole('option').allTextContents()).sort(), ['Cheshire Cat', 'Dormouse', 'Hatter', 'Queen of Hearts']);
    await page.getByRole('combobox').fill('Hatt');
    await page.getByRole('option',{name:'Hatter',exact:true}).click();
    await page.getByText('Line 2 of 24',{exact:true}).waitFor();
    assert.equal(await page.getByRole('combobox').count(),0);
    await page.getByRole('button',{name:'Previous',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Choose Hatter'}).getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'Choose another character'}).click();
    assert.equal(await page.getByRole('option',{name:'Hatter',exact:true}).count(),0);
    await page.getByRole('option',{name:'Dormouse',exact:true}).click();
    await page.getByText('Line 1 of 24',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Choose Hatter'}).count(),0);
    assert.equal(await page.getByRole('button',{name:'Choose Dormouse'}).getAttribute('aria-pressed'),'true');
    await page.getByRole('button',{name:'Choose another character'}).click();
    await page.getByRole('heading',{name:'Your transcript'}).click();
    assert.equal(await page.getByRole('combobox').count(),0);
    await page.getByRole('button',{name:'Choose another character'}).click();
    await page.getByRole('button',{name:'Choose another character'}).click();
    assert.equal(await page.getByRole('combobox').count(),0);
    await page.getByRole('button',{name:'Choose another character'}).click();
    await page.getByRole('combobox').fill('Guest');
    await page.getByRole('option',{name:'Guest',exact:true}).click();
    assert.equal(await page.getByRole('button',{name:'Choose Dormouse'}).count(),0);
    assert.equal(await page.getByRole('button',{name:'Choose Guest'}).getAttribute('aria-pressed'),'true');
    await page.screenshot({path:`${out}picker-replacement.png`,fullPage:true});
    // Return this line to narrator for the shared checks below.
    await page.getByRole('button',{name:'Choose Narrator'}).click();
  }
  await page.getByRole('button',{name:'Use narrator for remaining'}).click();
  assert.equal(await page.getByRole('button',{name:'Continue →'}).isEnabled(),true);
  await page.getByRole('button',{name:'Check your choices'}).click();
  assert.equal(await page.getByRole('region', {name:'By reader'}).count(), 0);
  await page.getByRole('button',{name:'Needs review 0'}).waitFor();
  await page.getByRole('button',{name:'Reviewed 24'}).waitFor();
  await page.screenshot({path:`${out}recheck-${width}-${appearance}.png`, fullPage:true});
  const first = page.locator('.ai-outcome').first();
  assert.equal(await first.getByRole('button',{name:'Choose Narrator'}).getAttribute('aria-pressed'), 'true');
  assert.equal(await first.getByRole('button',{name:'Restore AI choice'}).count(), 0);
  await first.getByRole('button',{name:'Choose Alice', exact:true}).click();
  assert.equal(await first.getByRole('button',{name:'Choose Alice', exact:true}).getAttribute('aria-pressed'), 'true');
  assert.equal(await first.getByRole('button',{name:'Choose Narrator'}).getAttribute('aria-pressed'), 'false');
  await page.getByRole('button',{name:'Next →'}).click();
  const originalAi = page.getByRole('button',{name:'Choose Alice', exact:true});
  assert.equal(await originalAi.getAttribute('aria-description'), 'AI choice');
  assert.match(await originalAi.innerText(), /✧/);
  await originalAi.click();
  assert.equal(await originalAi.getAttribute('aria-pressed'), 'true');
  assert.match(await originalAi.innerText(), /✓/);
  assert.doesNotMatch(await originalAi.innerText(), /✧/);
  assert.equal(await page.getByRole('button',{name:'Continue →'}).isEnabled(),true);
  await page.getByRole('button',{name:'Needs review 0'}).waitFor();
  if (width === 1440) {
    const backBox = await page.getByRole('button',{name:'← Back to readers'}).boundingBox();
    const filterBox = await page.getByRole('group',{name:'Filter AI results'}).boundingBox();
    assert(Math.abs(backBox.y - filterBox.y) < 3, 'Desktop filters should sit beside Back');
  }
  await page.waitForTimeout(250);
  const choiceVisuals = await page.locator('.dialogue-reader-option').evaluateAll(buttons => buttons.map(button => ({label:button.getAttribute('aria-label'),selected:button.getAttribute('aria-pressed'),className:button.className,background:getComputedStyle(button).backgroundColor,green:getComputedStyle(button).getPropertyValue('--green').trim()})));
  console.log(JSON.stringify({width,appearance,choiceVisuals}));
  await page.screenshot({path:`${out}chosen-${width}-${appearance}.png`, fullPage:true});
  await page.getByRole('button',{name:'Change strategy',exact:true}).click();
  const modal = page.getByRole('dialog',{name:'Change dialogue strategy?'});
  await modal.waitFor();
  assert.equal(await modal.getByRole('button',{name:'Keep reviewing'}).evaluate(el=>el===document.activeElement),true);
  await page.screenshot({path:`${out}confirm-${width}-${appearance}.png`, fullPage:false});
  await modal.getByRole('button',{name:'Keep reviewing'}).click();
  assert.equal(await originalAi.getAttribute('aria-pressed'), 'true');
  assert.deepEqual(errors,[]);
  metrics.push({width,appearance,overflow,editorFocus:'passed',bulkNarrator:'passed',directAiChoice:'passed',strategyConfirmation:'passed'});
  await page.close();
}
await browser.close();
await writeFile(`${out}metrics.json`, JSON.stringify(metrics,null,2));
console.log(JSON.stringify(metrics));
