/** Independent, read-only audit of the local synthetic Cast screens. */
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { chooseAppearance } from './appearance-controls.mjs';

const url = process.argv[2] ?? 'http://127.0.0.1:5179/studio.html';
const out = process.argv[3] ?? '../docs/matcha-next/evidence/cast-independent';
await mkdir(out, { recursive: true });
const browser = await chromium.launch();
const results = [];
try {
  for (const width of [1440, 390]) for (const appearance of ['light', 'dark']) {
    const page = await browser.newPage({ viewport: { width, height: 900 }, reducedMotion: 'reduce' });
    const errors = [], nativeDialogs = [], apiRequests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => { nativeDialogs.push(dialog.type()); void dialog.dismiss(); });
    await page.route('**/api/**', route => {
      if (!new URL(route.request().url()).pathname.startsWith('/api/')) return route.continue();
      apiRequests.push(route.request().url());
      return route.abort();
    });
    await page.goto(url);
    await page.getByText('Synthetic data · safe to explore', { exact: true }).waitFor();
    await chooseAppearance(page, appearance);
    const preview = page.getByRole('combobox', { name: 'Preview' });

    await preview.selectOption('cast-voices-dense');
    const board = page.getByRole('region', { name: 'Cast voice auditions' });
    await board.waitFor();
    const cards = board.locator('.voice-cast-tile');
    const rosterCount = await cards.count();
    assert.equal(rosterCount, 61, 'Narrator and 60 roles, including the group voice');
    const boardStyle = await board.evaluate(el => ({ display: getComputedStyle(el).display, columns: getComputedStyle(el).gridTemplateColumns }));
    assert.equal(boardStyle.display, 'grid');
    const longTile = page.getByRole('button', { name: 'Open Court witness 10 — keeper of the very long royal register voice' });
    assert(await longTile.isVisible());
    const longName = longTile.locator('.cast-roster-name');
    const longNameBounds = await longName.evaluate(el => ({ width: el.clientWidth, scrollWidth: el.scrollWidth, height: el.clientHeight, scrollHeight: el.scrollHeight }));
    assert(longNameBounds.scrollWidth <= longNameBounds.width + 1, 'Long name has no horizontal clipping');
    assert(longNameBounds.scrollHeight <= longNameBounds.height, 'Long name has no vertical clipping');
    assert(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 1, 'Dense roster has no horizontal overflow');
    await page.screenshot({ path: `${out}/roster-${width}-${appearance}.png` });
    await longTile.scrollIntoViewIfNeeded();
    await page.screenshot({ path: `${out}/long-name-${width}-${appearance}.png` });

    await preview.selectOption('cast-inspector');
    const dialog = page.getByRole('dialog', { name: 'Alice voice' });
    await dialog.waitFor();
    const first = dialog.getByRole('button', { name: 'Apply Audition 1' });
    const newest = dialog.getByRole('button', { name: 'Apply Audition 3' });
    assert.equal(await newest.getAttribute('aria-pressed'), 'false');
    await first.click();
    assert.equal(await first.getAttribute('aria-pressed'), 'true');
    assert.equal(await newest.getAttribute('aria-pressed'), 'false');
    assert(await dialog.getByText('✓ Applied').isVisible(), 'One-click audition applies without a second approval');
    assert(await dialog.isVisible(), 'Audition selection keeps the inspector open');
    await dialog.screenshot({ path: `${out}/audition-applied-${width}-${appearance}.png` });
    await dialog.getByRole('button', { name: 'Create a new audition' }).click();
    assert.equal(await dialog.locator('.voice-candidates-section').count(), 0);
    assert(await dialog.getByRole('group', { name: 'Voice traits' }).isVisible());
    assert(await dialog.getByLabel('Performance notes').inputValue(), 'Voice direction should be populated');
    await dialog.screenshot({ path: `${out}/ghost-${width}-${appearance}.png` });
    const generateAudition = dialog.getByRole('button', { name: 'Generate new audition →' });
    await generateAudition.click();
    const regenerateConfirmation = page.getByRole('dialog', { name: 'Create a replacement audition?' });
    assert(await regenerateConfirmation.isVisible());
    await page.keyboard.press('Escape');
    await regenerateConfirmation.waitFor({ state: 'hidden' });
    assert(await generateAudition.evaluate(el => el === document.activeElement), 'Canceling audition regeneration restores New voice action focus');
    await dialog.getByRole('button', { name: 'Back to auditions' }).click();
    assert.equal(await first.getAttribute('aria-pressed'), 'true', 'Back keeps the applied candidate');
    assert.equal(await dialog.locator('.voice-candidate-tile').count(), 3, 'Canceled regeneration keeps the audition set');
    assert.equal(await dialog.getByRole('group', { name: 'Voice traits' }).count(), 0);
    await dialog.getByRole('button', { name: 'Create a new audition' }).click();
    await dialog.getByRole('button', { name: 'Generate new audition →' }).click();
    await regenerateConfirmation.getByRole('button', { name: 'Create audition →' }).click();
    const newestPlay = dialog.getByRole('button', { name: 'Play Audition 4' });
    await newestPlay.waitFor();
    assert(await newestPlay.evaluate(el => el === document.activeElement), 'Generated audition returns to the list with Play focused');
    assert.equal(await dialog.locator('.voice-candidate-tile').count(), 4);
    await dialog.screenshot({ path: `${out}/audition-generated-${width}-${appearance}.png` });
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
    assert(await page.getByRole('button', { name: 'Open Alice voice' }).evaluate(el => el === document.activeElement), 'Inspector Escape restores tile focus');

    await preview.selectOption('cast-accepted');
    await page.getByRole('heading', { name: 'Cast and voices ready' }).waitFor();
    const change = page.getByRole('button', { name: /Change settings/ });
    await change.click();
    const confirmation = page.getByRole('dialog', { name: 'Change the cast?' });
    assert(await confirmation.isVisible());
    assert(await confirmation.evaluate(el => el.contains(document.activeElement)), 'Focus stays inside the confirmation');
    await page.keyboard.press('Tab');
    assert(await confirmation.getByRole('button', { name: 'Keep current cast' }).evaluate(el => el === document.activeElement), 'Cancel is the first keyboard action');
    await page.keyboard.press('Escape');
    await confirmation.waitFor({ state: 'hidden' });
    const replacementFocusRestored = await change.evaluate(el => el === document.activeElement);
    assert(replacementFocusRestored, 'Escape returns focus to Change settings');
    await change.click();
    await confirmation.getByRole('button', { name: /Change cast/ }).click();
    await page.getByRole('heading', { name: 'Voices' }).waitFor();
    assert(await page.getByRole('region', { name: 'Cast voice auditions' }).isVisible(), 'Change settings returns to voices');
    await page.getByRole('button', { name: /Edit cast/ }).click();
    await page.getByRole('heading', { name: 'Review the cast.' }).waitFor();
    assert.equal(await page.getByRole('button', { name: /Review cast & voices/ }).count(), 0, 'Change settings opens populated editor without another scan');
    assert(await page.locator('.cast-tile').count() > 0, 'Existing cast members remain populated');
    const reclassify = page.getByRole('button', { name: 'Reclassify from Dialogue' });
    await reclassify.click();
    const secondConfirmation = page.getByRole('dialog', { name: 'Reclassify source labels?' });
    assert(await secondConfirmation.isVisible());
    await secondConfirmation.getByRole('button', { name: 'Keep current cast' }).click();
    assert.equal(await secondConfirmation.count(), 0, 'Cancel closes without reclassifying');
    const reclassifyFocusRestored = await reclassify.evaluate(el => el === document.activeElement);
    assert(reclassifyFocusRestored, 'Cancel returns focus to Reclassify from Dialogue');
    await page.screenshot({ path: `${out}/accepted-settings-${width}-${appearance}.png` });
    await reclassify.click();
    await secondConfirmation.getByRole('button', { name: 'Reclassify labels →' }).click();
    await page.getByRole('heading', { name: 'Build the cast.' }).waitFor();
    assert(await page.getByRole('region', { name: 'Cast members' }).isVisible(), 'Reclassification returns to Cast identity review');
    assert.equal(await page.getByRole('region', { name: 'Cast voice auditions' }).count(), 0);
    await page.screenshot({ path: `${out}/reclassified-${width}-${appearance}.png` });
    assert(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth) <= 1);
    assert.deepEqual(nativeDialogs, []);
    assert.deepEqual(errors, []);
    assert.deepEqual(apiRequests, []);
    results.push({ width, appearance, roster: rosterCount, boardStyle, longNameBounds, oneClickApply: true, generatedAuditionReturnsToList: true, populatedSettings: true, reclassifyReturnsToCast: true, dialogs: { custom: true, replacementFocusRestored, reclassifyFocusRestored, regenerationFocusRestored: true }, nativeDialogs, errors, apiRequests });
    await page.close();
  }
} finally { await browser.close(); }
await writeFile(`${out}/report.json`, JSON.stringify({ url, executedAt: new Date().toISOString(), scope: 'Independent local synthetic Cast UI audit; no provider operations or real book mutations.', results }, null, 2));
console.log(JSON.stringify(results, null, 2));
