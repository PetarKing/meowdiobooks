import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
import {chooseAppearance} from './appearance-controls.mjs';
const base=process.argv[2]??'http://127.0.0.1:5179/studio.html';
const out=process.argv[3]??'../.review-evidence/cast';
await mkdir(out,{recursive:true});
const browser=await chromium.launch();const results=[];
try {for(const width of [1440,390]) for(const appearance of ['light','dark']) {
 const page=await browser.newPage({viewport:{width,height:width>600?1000:844},reducedMotion:'reduce'});
 const errors=[],apiRequests=[],nativeDialogs=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',d=>{nativeDialogs.push(d.message());void d.dismiss()});
 await page.route('**/api/**',r=>{if(!new URL(r.request().url()).pathname.startsWith('/api/')) return r.continue();apiRequests.push(r.request().url());return r.abort()});
 await page.goto(base);await page.getByText('Synthetic data · safe to explore',{exact:true}).waitFor();
 await chooseAppearance(page,appearance);
 const preview=page.getByRole('combobox',{name:'Preview',exact:true});
 await preview.selectOption('cast-voices');await page.getByRole('region',{name:'Cast voice auditions'}).waitFor();
 await page.evaluate(()=>document.fonts.ready);
 await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});
 const axe=async selector=>page.evaluate(async selector=>(await window.axe.run(selector)).violations.map(v=>({id:v.id,targets:v.nodes.map(n=>n.target)})),selector);
 assert.deepEqual(await axe('.voice-cast-workbench'),[],'Roster accessibility');
 const board=page.locator('.voice-cast-board');
 const columns=await board.evaluate(e=>getComputedStyle(e).gridTemplateColumns.split(' ').length);
 assert(columns>=(width>600?3:2),`Roster has ${columns} columns at ${width}`);
 await page.screenshot({path:`${out}/roster-${width}-${appearance}.png`,fullPage:true});
 await preview.selectOption('cast-inspector');const dialog=page.getByRole('dialog',{name:'Alice voice'});await dialog.waitFor();
 assert.equal(await dialog.getByRole('button',{name:/Approve Audition/}).count(),0);
 assert.equal(await dialog.getByRole('group',{name:'Voice traits'}).count(),0);
 const earlier=dialog.getByRole('button',{name:'Apply Audition 1'});await earlier.click();
 assert.equal(await earlier.getAttribute('aria-pressed'),'true');assert(await dialog.isVisible());
 assert.deepEqual(await axe('.voice-inspector'),[],'Audition inspector accessibility');
 await page.screenshot({path:`${out}/auditions-${width}-${appearance}.png`});
 const inspectorBounds=await dialog.boundingBox();
 assert(inspectorBounds && (width>600?inspectorBounds.height<850:Math.abs(inspectorBounds.height-844)<2),'Inspector fits its content on desktop and fills the phone');
 await dialog.getByRole('button',{name:'Create a new audition'}).click();
 assert(await dialog.getByRole('group',{name:'Voice traits'}).isVisible());
 assert.equal(await dialog.evaluate(e=>e.scrollTop),0,'Switching to Ghost resets inspector scroll');
 assert.equal(await dialog.getByRole('button',{name:'Apply Audition 1'}).count(),0);
 assert.deepEqual(await axe('.voice-inspector'),[],'New voice mode accessibility');
 await page.screenshot({path:`${out}/ghost-${width}-${appearance}.png`});
 await dialog.getByRole('button',{name:'Back to auditions'}).click();
 assert(await dialog.getByRole('button',{name:'Apply Audition 1'}).isVisible());
 await dialog.getByRole('button',{name:'Close voice'}).click();await dialog.waitFor({state:'hidden'});
 await preview.selectOption('cast-accepted');const change=page.getByRole('button',{name:'Change settings →'});await change.click();
 const confirmation=page.getByRole('dialog',{name:'Change the cast?'});await confirmation.waitFor();
 assert.deepEqual(await axe('.cast-confirmation-modal'),[],'Confirmation accessibility');
 await page.screenshot({path:`${out}/confirmation-${width}-${appearance}.png`});
 await confirmation.press('Escape');
 assert(await change.evaluate(e=>e===document.activeElement),'Escape returns focus to Change settings');
 await change.click();
 await confirmation.getByRole('button',{name:'Keep current cast'}).click();assert(await change.isVisible());
 assert(await change.evaluate(e=>e===document.activeElement),'Cancel returns focus to Change settings');
 await change.click();await page.getByRole('button',{name:'Change cast →'}).click();
 await page.getByRole('region',{name:'Cast voice auditions'}).waitFor();
 await page.getByRole('button',{name:/Edit cast/}).click();
 await page.getByRole('region',{name:'Cast members'}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Review cast & voices →'}).count(),0);
 await page.getByRole('button',{name:'Cancel cast edits'}).click();
 await page.getByRole('region',{name:'Cast voice auditions'}).waitFor();
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);assert(overflow<=1);
 assert.deepEqual(errors,[]);assert.deepEqual(apiRequests,[]);assert.deepEqual(nativeDialogs,[]);
 results.push({width,appearance,rosterColumns:columns,oneClickApply:true,voiceCreationMode:true,designedConfirmation:true,confirmationFocusRestored:true,directVoicesReturn:true,editCastAvailable:true,axe:'0 scoped violations across roster, inspector, voice creation and confirmation',overflow,errors,apiRequests,nativeDialogs});
 await page.close();
}}finally{await browser.close()}
await writeFile(`${out}/report.json`,JSON.stringify({base,executedAt:new Date().toISOString(),scope:'Synthetic fixture; no backend voice generation, persisted revision, or real audio audition.',results},null,2));
console.log(JSON.stringify(results,null,2));
